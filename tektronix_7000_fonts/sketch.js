// Monoline vector fonts from the Tektronix 7000-series oscilloscope
// character generator EPROM readout board. Extracted from Holger's PDFs
// `Font_160-2997-00.pdf` and `Font_160-2997-01.pdf`, which reproduce
// Tektronix readout fonts 160-2997-00 (1984) and 160-2997-01 (1986).
//
// Background: https://w140.com/tekwiki/wiki/7000_series_readout_system.
// The source PDF streams store page-rotated line segments; the coordinates
// below are normalized to displayed glyph coordinates with positive Y down.

function setup() {
  createCanvas(1024, 720);
  pixelDensity(2);

  buildGlyphMap(tektronix7000Font1984);
  buildGlyphMap(tektronix7000Font1986);
}

function keyPressed() {
  if (key === 's' || key === 'S') {
    saveCanvas('tektronix_7000_fonts', 'png');
  }
}


function draw() {
  background('black');
  strokeWeight(1.0);
  strokeJoin(ROUND);
  strokeCap(ROUND);

  drawFontBlock(tektronix7000Font1984, 100, 125);
  drawFontBlock(tektronix7000Font1986, 100, 425);

  stroke("white"); 
  drawString(tektronix7000Font1984, "HELLO WORLD", 455,79,  21, 0.9);
  drawString(tektronix7000Font1986, "HELLO WORLD", 455,379, 21, 0.9);
}


function drawFontBlock(font, x, y) {
  noStroke();
  fill(128);
  textFont('Arial');
  textSize(15);
  text(font.title, x, y - 28);

  stroke('white');
  noFill();

  const TEKTRONIX_7000_SUPPORTED_CHARS = [
    'ABCDEFGHIJKLM',
    'NOPQRSTUVWXYZ',
    '0123456789+-/',
    'cdpmnμΩΔ<>↓'
  ];

  const size = 42;
  const spacing = 1.0
  const lineHeight = 1.3;
  let ty = y;
  for (const row of TEKTRONIX_7000_SUPPORTED_CHARS) {
    drawString(font, row, x, ty, size, spacing);
    ty += size * lineHeight;
  }
}


function buildGlyphMap(font) {
  font.map = new Map();
  for (const glyph of font.glyphs) {
    if (!font.map.has(glyph.char)) {
      font.map.set(glyph.char, glyph);
    }
  }
  font.map.set(' ', { char: ' ', strokes: [] });
}


function getGlyph(font, ch) {
  return font.map.get(ch);
}


function drawString(font, str, x, y, size, spacing = 1.15, lineHeight = 1.3) {
  const sca = size / TEKTRONIX_7000_H;
  const advancePx = TEKTRONIX_7000_ADVANCE * sca * spacing;
  let cx = x;
  let cy = y;

  for (const ch of str) {
    if (ch === '\n') {
      cx = x;
      cy += size * lineHeight;
      continue;
    }
    drawGlyph(font, ch, cx, cy, size);
    cx += advancePx;
  }
}


function drawGlyph(font, ch, gx, gy, size) {
  const glyph = getGlyph(font, ch);
  if (!glyph) return;

  const sca = size / TEKTRONIX_7000_H;
  for (const stroke of glyph.strokes) {
    if (!stroke.length) continue;

    if (stroke.length === 2 && samePoint(stroke[0], stroke[1])) {
      point(gx + stroke[0][0] * sca, gy + stroke[0][1] * sca);
      continue;
    }

    beginShape();
    for (const [px, py] of stroke) {
      vertex(gx + px * sca, gy + py * sca);
    }
    endShape();
  }
}


function samePoint(a, b) {
  return a[0] === b[0] && a[1] === b[1];
}


